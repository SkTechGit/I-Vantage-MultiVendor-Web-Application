import mongoose from "mongoose";

const professionalCategorySchema = new mongoose.Schema(
  {
    slug: {
      type: String,
      required: true,
      unique: true,
      lowercase: true,
      trim: true,
      index: true,
    },
    name: {
      type: String,
      required: true,
      trim: true,
    },
    label: {
      type: String,
      required: true,
      trim: true,
    },
    description: {
      type: String,
      trim: true,
      default: "",
    },
    iconKey: {
      type: String,
      default: "Briefcase",
    },
    sortOrder: {
      type: Number,
      default: 0,
      index: true,
    },
    isActive: {
      type: Boolean,
      default: true,
      index: true,
    },
  },
  {
    timestamps: true,
  }
);

const ProfessionalCategory =
  mongoose.models.ProfessionalCategory ||
  mongoose.model("ProfessionalCategory", professionalCategorySchema);

export default ProfessionalCategory;
